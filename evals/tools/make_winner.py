"""Build the winner-prediction case from published tests with a clear result.
Picks every A/B record that is a loss, or a win with a published confidence of 95% or more, writes them to
evals/holdout.txt (stage.py --holdout removes them from the pack copy), shows each test as version A and B
in a seeded random order with no company name or lift, and writes the answer key.
Usage: make_winner.py [--check]"""
import json
import random
import sys
from pathlib import Path

EVALS = Path(__file__).resolve().parents[1]
TESTS = EVALS.parent / "skills/cro/evidence/tests"


def clear(rec):
    r, s = rec["result"], rec["significance"] or {}
    if rec.get("research_type", "ab-test") != "ab-test" or r.get("desired_direction", "increase") != "increase":
        return False
    return r["direction"] == "loss" or (r["direction"] == "win" and (s.get("confidence_pct") or 0) >= 95)


def build():
    recs = [json.loads(p.read_text()) for p in sorted(TESTS.glob("*.json"))]
    recs = [r for r in recs if clear(r)]
    rng = random.Random(20261017)
    rng.shuffle(recs)
    sides = (["A", "B"] * len(recs))[: len(recs)]
    rng.shuffle(sides)
    tests, lines = [], []
    for n, (rec, winner) in enumerate(zip(recs, sides), 1):
        tid = f"t{n:02d}"
        winner_is = "variant" if rec["result"]["direction"] == "win" else "control"
        variant_side = winner if winner_is == "variant" else ("B" if winner == "A" else "A")
        a, b = (rec["change"]["variant"], rec["change"]["control"]) if variant_side == "A" else (rec["change"]["control"], rec["change"]["variant"])
        tests.append({"id": tid, "evidence_id": rec["id"], "winner": winner, "winner_is": winner_is})
        lines.append(f"{tid}. {rec['industry']} ({rec['business_type']}), {rec['page_type']} page, metric: {rec['result']['metric']}.\n"
                     f"    A: {a}\n    B: {b}")
    prompt = (
        "Below are real A/B tests that companies ran and published. For each one, predict which version, A or B, "
        "got the higher result on the stated metric (higher is better for every metric listed). One of the two is "
        "the original page, but the order is random. Use whatever CRO knowledge and method you have. Do not search "
        "the web.\n\n" + "\n\n".join(lines) +
        '\n\nGive a one-line reason for each, then end with one JSON code block mapping every id to "A" or "B", '
        'for example {"t01": "A", "t02": "B"}.\n')
    graders = "".join(
        f"  - name: {t['id']}\n    type: regex\n    pattern: {json.dumps(chr(34) + t['id'] + chr(34) + r'\s*:\s*' + chr(34) + t['winner'] + chr(34))}\n"
        for t in tests)
    case = ("# Generated by evals/tools/make_winner.py. Do not edit by hand.\n"
            'schema_version: "1.1"\nname: winner\n'
            "description: Predict the winner of published A/B tests held out from the pack. Score = accuracy; a coin flip scores 0.5.\n"
            "tags: [winner]\nruns: 3\nexecution:\n  max_turns: 40\n  timeout_seconds: 900\n"
            "  allowed_tools: [Read, Glob, Grep, Skill]\n"
            "  prompt: " + json.dumps(prompt) + "\ngraders:\n" + graders +
            "  - name: pack-used\n    type: tool_used\n    tool: Skill\n    arm: with-only\n    input_match: '\"skill\"\\s*:\\s*\"(?:[\\w-]+:)?cro'\n")
    holdout = "# Published tests held out from the pack copy for the winner case (generated by make_winner.py)\n" + "".join(t["evidence_id"] + "\n" for t in tests)
    key = json.dumps({"tests": tests}, indent=2) + "\n"
    return {EVALS / "winner/case.yaml": case, EVALS / "holdout.txt": holdout, EVALS / "answer-keys/winner.json": key}


if __name__ == "__main__":
    stale = []
    for path, text in build().items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(EVALS)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print("wrote", path.relative_to(EVALS))
    if stale:
        sys.exit("out of date (run evals/tools/make_winner.py): " + ", ".join(stale))
