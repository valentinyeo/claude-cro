"""Write one defect-finding eval case per planted fixture. Graders reuse the answer-key patterns.
Usage: make_cases.py [--check]"""
import json
import sys
from pathlib import Path

EVALS = Path(__file__).resolve().parents[1]

PROMPT = (
    "The landing page of {site} is saved as index.html in the current folder (a snapshot: the live site is not "
    "reachable from here, so do not fetch it). Do a conversion review of this page: find what stops visitors "
    "from signing up or buying. For each problem, quote the exact text from the page that shows it.\n\n"
    'End your answer with one JSON code block: a list of objects {{"problem": "...", "quote": "exact text copied '
    'from the page"}}, most serious first.\n')

SETUP = """#!/bin/bash
# Copies the planted fixture into the empty eval workspace.
set -euo pipefail
cp "$(dirname "$0")/../fixtures/{fixture}" index.html
"""


def build():
    out = {}
    for key_file in sorted((EVALS / "answer-keys").glob("*.json")):
        if key_file.name == "winner.json":
            continue
        name = key_file.stem
        key = json.loads(key_file.read_text())
        site = name.removesuffix(".subtle").removesuffix(".blind")
        graders = "".join(f"  - name: {d['id']}\n    type: regex\n    flags: i\n    pattern: {json.dumps(d['found'])}\n"
                          for d in key["defects"])
        case = ("# Generated by evals/tools/make_cases.py from answer-keys/" + key_file.name + ". Do not edit by hand.\n"
                f'schema_version: "1.1"\nname: defects-{name}\n'
                f"description: Find 5 planted {key['tier']} conversion defects on a snapshot of {site}. Score = share found.\n"
                f"tags: [defects, {key['tier']}]\nruns: 3\ncontext:\n  scaffold_script: setup.sh\nexecution:\n"
                "  max_turns: 40\n  timeout_seconds: 900\n  allowed_tools: [Read, Glob, Grep, Skill]\n"
                "  prompt: " + json.dumps(PROMPT.format(site=site)) + "\ngraders:\n" + graders +
                "  - name: pack-used\n    type: tool_used\n    tool: Skill\n    arm: with-only\n    input_match: '\"skill\"\\s*:\\s*\"(?:[\\w-]+:)?cro'\n")
        out[EVALS / f"defects-{name}/case.yaml"] = case
        out[EVALS / f"defects-{name}/setup.sh"] = SETUP.format(fixture=Path(key["fixture"]).name)
    return out


if __name__ == "__main__":
    stale = []
    for path, text in build().items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(EVALS)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            path.chmod(0o755 if path.suffix == ".sh" else 0o644)
            print("wrote", path.relative_to(EVALS))
    if stale:
        sys.exit("out of date (run evals/tools/make_cases.py): " + ", ".join(stale))
